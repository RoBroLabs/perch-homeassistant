"""Write protocol/vectors/let_in.json: fixed inputs and outputs for the let-in seal.

Run from the repository root with the test virtual environment:
`.venv/bin/python scripts/make_let_in_vectors.py`. Uses `cryptography` (OpenSSL).
Every key, nonce, credential and PIN here is a public test value.
"""

from __future__ import annotations

import base64
import hashlib
import json
from pathlib import Path
import sys

from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from custom_components.perch import crypto  # noqa: E402

h = bytes.fromhex
base = json.loads((ROOT / "protocol" / "vectors" / "crypto.json").read_text())["inputs"]
inputs = {
    "tv_private_key": base["tv_private_key"],
    "server_ephemeral_private_key": base["server_ephemeral_private_key"],
    "challenge": base["challenge"],
    "credential": base["credential"],
    "let_in_ephemeral_private_key": bytes(range(0x61, 0x81)).hex(),
    "let_in_aead_nonce": bytes(range(0x30, 0x3C)).hex(),
    "pin": "13572468",
    "command_id": 11,
}
tv = X25519PrivateKey.from_private_bytes(h(inputs["tv_private_key"]))
server = X25519PrivateKey.from_private_bytes(h(inputs["server_ephemeral_private_key"]))
eph = X25519PrivateKey.from_private_bytes(h(inputs["let_in_ephemeral_private_key"]))
tv_pub = tv.public_key().public_bytes_raw()
server_pub = server.public_key().public_bytes_raw()
eph_pub = eph.public_key().public_bytes_raw()
challenge, credential = h(inputs["challenge"]), h(inputs["credential"])
cid = inputs["command_id"]
shared = eph.exchange(server.public_key())
hash_raw = hashlib.sha256(credential).digest()
sealed = crypto.seal_pin(
    inputs["pin"], server_pub, credential, challenge, tv_pub, cid,
    ephemeral=eph, aead_nonce=h(inputs["let_in_aead_nonce"]),
)
outputs = {
    "tv_public_key": tv_pub.hex(),
    "server_key": server_pub.hex(),
    "let_in_ephemeral_public_key": eph_pub.hex(),
    "shared": shared.hex(),
    "credential_hash": hash_raw.hex(),
    "ikm": (shared + hash_raw).hex(),
    "info": (b"perch-letin-v1" + eph_pub + server_pub + tv_pub).hex(),
    "key": crypto.let_in_key(shared, hash_raw, challenge, eph_pub, server_pub, tv_pub).hex(),
    "aad": crypto.let_in_aad(challenge, cid).hex(),
    "plaintext": inputs["pin"].encode().ljust(16, b"\0").hex(),
    "sealed_pin": sealed.hex(),
    "sealed_pin_base64": base64.b64encode(sealed).decode(),
    "open_with_command_id_12_expect": "open_fails",
    "open_with_wrong_stored_hash_expect": "open_fails",
}
assert crypto.open_sealed_pin(server, hash_raw.hex(), challenge, tv_pub, cid, sealed) == inputs["pin"]
assert crypto.open_sealed_pin(server, hash_raw.hex(), challenge, tv_pub, 12, sealed) is None
assert crypto.open_sealed_pin(server, base["wrong_stored_credential_hash"], challenge, tv_pub, cid, sealed) is None
doc = {
    "notes": "All binary values are lowercase hex. Every key, nonce, credential and PIN here is a public test value; never use them outside tests. Inputs shared with crypto.json use the same values. Generated by scripts/make_let_in_vectors.py (Python cryptography); the TV side must reproduce them with CryptoKit.",
    "inputs": inputs,
    "outputs": outputs,
}
(ROOT / "protocol" / "vectors" / "let_in.json").write_text(json.dumps(doc, indent=2, sort_keys=True) + "\n")
print(outputs["sealed_pin_base64"])
